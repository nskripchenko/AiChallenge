package dev.skrip.aichallenge.prompts

object PromptFactory {

    fun buildDirectPrompt(task: String): String = task

    fun buildStepByStepPrompt(task: String): String = """
        |$task
        |
        |Решай пошагово. Сначала проанализируй задачу, затем рассмотри возможные подходы, и только потом дай финальный ответ.
    """.trimMargin()

    fun buildPromptGenerationRequest(task: String): String = """
        |Ты — эксперт по промпт-инжинирингу. Твоя задача — создать оптимальный промпт для решения следующей задачи.
        |
        |Задача:
        |$task
        |
        |Создай детальный промпт, который поможет AI максимально эффективно решить эту задачу.
        |Промпт должен включать:
        |1. Чёткую формулировку задачи
        |2. Инструкции по формату ответа
        |3. Подсказки для структурирования решения
        |
        |Верни ТОЛЬКО промпт, без пояснений.
    """.trimMargin()

    fun buildExpertsPrompt(task: String): String = """
        |Представь, что ты — совет из трёх экспертов, обсуждающих задачу:
        |
        |1. **Аналитик** — разбирает условия задачи, выделяет ключевые данные и ограничения
        |2. **Стратег** — предлагает различные подходы к решению и оценивает их
        |3. **Критик** — проверяет логику, ищет ошибки и подтверждает правильность
        |
        |Задача:
        |$task
        |
        |Проведи обсуждение от лица всех трёх экспертов, затем дай согласованный финальный ответ.
    """.trimMargin()
}
